CREATE TABLE IF NOT EXISTS bike_type_codes (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  type_code TEXT NOT NULL,
  maker TEXT NOT NULL,
  model TEXT NOT NULL,
  cc INTEGER NOT NULL,
  aliases TEXT[] DEFAULT ARRAY[]::TEXT[],
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now(),
  UNIQUE(type_code)
);

CREATE INDEX IF NOT EXISTS idx_bike_type_codes_maker ON bike_type_codes(maker);
CREATE INDEX IF NOT EXISTS idx_bike_type_codes_model ON bike_type_codes(model);
CREATE INDEX IF NOT EXISTS idx_bike_type_codes_cc ON bike_type_codes(cc);

